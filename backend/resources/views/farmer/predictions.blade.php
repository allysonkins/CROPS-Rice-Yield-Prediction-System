        viewModal.addEventListener('show.bs.modal', function(event) {
            const button = event.relatedTarget;
            if (!button) return;
            const predictionId = button.getAttribute('data-prediction-id');
            if (!predictionId) return;

            document.getElementById('viewModalLoading').style.display = 'block';
            document.getElementById('viewModalContent').style.display = 'none';
            document.getElementById('viewModalContent').innerHTML = '';

            fetch('/farmer/predictions/' + predictionId, {
                headers: { 'X-Requested-With': 'XMLHttpRequest' }
            })
            .then(response => {
                if (!response.ok) throw new Error('HTTP ' + response.status);
                return response.text();
            })
            .then(html => {
                document.getElementById('viewModalLoading').style.display = 'none';
                document.getElementById('viewModalContent').style.display = 'block';
                document.getElementById('viewModalContent').innerHTML = html;
            })
            .catch(() => {
                document.getElementById('viewModalLoading').style.display = 'none';
                document.getElementById('viewModalContent').style.display = 'block';
                document.getElementById('viewModalContent').innerHTML =
                    '<div class="alert alert-danger"><i class="bi bi-exclamation-triangle"></i> Failed to load prediction details.</div>';
